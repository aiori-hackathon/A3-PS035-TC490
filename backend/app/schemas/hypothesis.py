"""
Fault hypothesis domain models for the NEXORA diagnostic system.

A FaultHypothesis represents a candidate explanation for an observed incident,
generated by the diagnostic engine from topology-aware evidence analysis.

DESIGN INVARIANTS:
- FaultHypothesis.rule_score is a heuristic rank score, NOT a calibrated probability.
  It must not be presented or interpreted as a statistical confidence value.
- Ground-truth fault labels (from FaultInjectionRecord) must NEVER appear as fields
  in FaultHypothesis or be used as input features during live inference.
- Supporting and contradictory evidence IDs reference EvidenceRecord.evidence_id values.
- The hypothesis engine may abstain (see DiagnosisStatus.INSUFFICIENT_EVIDENCE).
"""

from __future__ import annotations

from enum import Enum

from pydantic import BaseModel, ConfigDict, Field, model_validator

# ---------------------------------------------------------------------------
# Enumerations
# ---------------------------------------------------------------------------


class FaultType(str, Enum):
    """The five supported fault categories for PS-035 evaluation."""

    LINK_FAILURE = "LINK_FAILURE"
    ROUTER_FAILURE = "ROUTER_FAILURE"
    OSPF_CONFIGURATION_MISMATCH = "OSPF_CONFIGURATION_MISMATCH"
    PACKET_LOSS = "PACKET_LOSS"
    HIGH_LATENCY = "HIGH_LATENCY"


class FaultLocationKind(str, Enum):
    """Whether the suspected fault is on a router or a link."""

    ROUTER = "ROUTER"
    LINK = "LINK"


# ---------------------------------------------------------------------------
# Fault location
# ---------------------------------------------------------------------------


class FaultLocation(BaseModel):
    """Identifies the suspected faulty network component."""

    model_config = ConfigDict(extra="forbid")

    kind: FaultLocationKind = Field(
        description="Whether the fault is suspected on a router or a link.",
    )
    component_id: str = Field(
        description="Router ID (e.g. 'R3') or Link ID (e.g. 'L34') of the "
        "suspected faulty component.",
        min_length=1,
        max_length=16,
    )
    affected_routers: list[str] = Field(
        default_factory=list,
        description="Router IDs directly implicated by this fault location "
        "(e.g. both endpoints of a suspected failed link).",
    )

    @model_validator(mode="after")
    def validate_kind_matches_component_id(self) -> FaultLocation:
        if self.kind == FaultLocationKind.ROUTER:
            import re
            if not re.match(r"^R[1-9][0-9]*$", self.component_id):
                raise ValueError(
                    f"FaultLocation kind=ROUTER but component_id {self.component_id!r} "
                    "does not match router pattern 'R<N>'"
                )
        elif self.kind == FaultLocationKind.LINK:
            import re
            if not re.match(r"^L[0-9]{2,}$", self.component_id):
                raise ValueError(
                    f"FaultLocation kind=LINK but component_id {self.component_id!r} "
                    "does not match link pattern 'L<NN>'"
                )
        return self


# ---------------------------------------------------------------------------
# Fault hypothesis
# ---------------------------------------------------------------------------


class FaultHypothesis(BaseModel):
    """A single candidate fault hypothesis generated by the diagnostic engine.

    Hypotheses are produced from topology graph analysis and rule-based scoring.
    They are ranked and packaged into a DiagnosisResult.

    IMPORTANT: rule_score is a dimensionless heuristic rank value produced by
    deterministic rules. It is NOT a calibrated probability. Do not present it
    as P(fault | evidence).
    """

    model_config = ConfigDict(extra="forbid")

    hypothesis_id: str = Field(
        description="Unique identifier for this hypothesis within a diagnosis run.",
        min_length=1,
    )
    incident_id: str = Field(
        description="Incident ID this hypothesis addresses.",
        min_length=1,
    )
    fault_type: FaultType = Field(
        description="Type of fault this hypothesis proposes.",
    )
    fault_location: FaultLocation = Field(
        description="Suspected faulty network component.",
    )
    rule_score: float = Field(
        ge=0.0,
        le=1.0,
        description="Heuristic rule-based score in [0.0, 1.0]. "
        "Higher = stronger evidence alignment. "
        "NOT a calibrated statistical probability.",
    )
    supporting_evidence_ids: list[str] = Field(
        default_factory=list,
        description="Evidence IDs whose observations are consistent with this hypothesis.",
    )
    contradictory_evidence_ids: list[str] = Field(
        default_factory=list,
        description="Evidence IDs whose observations contradict this hypothesis.",
    )
    missing_evidence_descriptions: list[str] = Field(
        default_factory=list,
        description="Human-readable descriptions of evidence that would be needed "
        "to confirm or refute this hypothesis but has not been collected.",
    )
    counterfactual_verified: bool | None = Field(
        default=None,
        description="True if counterfactual verification confirmed this hypothesis, "
        "False if it refuted it, None if not yet attempted.",
    )
    reasoning_trace: list[str] = Field(
        default_factory=list,
        description="Ordered list of rule names or inference steps that produced "
        "this hypothesis. Supports auditability.",
    )

    @model_validator(mode="after")
    def validate_no_overlapping_evidence(self) -> FaultHypothesis:
        supporting = set(self.supporting_evidence_ids)
        contradictory = set(self.contradictory_evidence_ids)
        overlap = supporting & contradictory
        if overlap:
            raise ValueError(
                f"Evidence IDs cannot be both supporting and contradictory: {overlap}"
            )
        return self
